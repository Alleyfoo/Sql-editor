"""LLM SQL Assistant — heuristic vs LLM comparison page.

This page demonstrates the value the LLM adds over the offline heuristic
fast path (``src.heuristic_nl``).  It runs the *same* natural-language
input through both paths and shows the user the two resulting
:class:`~src.query_model.QueryModel` plans side by side.

Safety: nothing on this page executes SQL.  Both paths produce a
``QueryModel``; the SQL is generated by ``QueryModel.to_sql()`` and shown
to the user for inspection only.  The user clicks "Use this plan" to
hand the chosen plan off to the Studio page, where the existing
``▶ Run query`` button runs it through the same executor blocklist as
every other query in the app.

Architecture
------------
- The heuristic path is local, free, and runs eagerly on every input.
- The LLM path uses the production ``nl_to_query_model`` entry point,
  with the same ``LLMConfig`` (provider, model, host) the Studio page is
  using — the ``⚙ LLM`` popover in the header controls both pages.
- The "Use this plan" button writes the chosen ``QueryModel`` into
  ``st.session_state.model`` / ``st.session_state.last_sql`` and calls
  ``st.switch_page`` back to the Studio, where the SQL preview is
  already populated.
"""

